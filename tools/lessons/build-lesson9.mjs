// Turns the proofread draft tools/lessons/lesson9-tenses.json into src/data/lesson9-tenses.ts.
// Usage: node tools/lessons/build-lesson9.mjs   (re-run after editing the draft)
import { readFileSync, writeFileSync } from 'node:fs';

const draft = JSON.parse(readFileSync(new URL('lesson9-tenses.json', import.meta.url), 'utf8'));
const stageIds = draft.stages.map(stage => `'${stage.id}'`).join(' | ');
const body = `// Generated by tools/lessons/build-lesson9.mjs from tools/lessons/lesson9-tenses.json. Edit the draft, not this file.
// Original A2–B2 practice. options[0] is the answer; ChoiceCard shuffles options.
export type TenseStage = ${stageIds};
export interface TenseExercise {
  id: string; stage: TenseStage; level: 'A2' | 'B1' | 'B2';
  sentence: string; options: string[]; trans: string; explain: string;
}
export interface ConceptSection { title: string; lines: string[] }
export const STAGES: { id: TenseStage; label: string; hint: string }[] = ${JSON.stringify(draft.stages, null, 2)};

export const tenseExercises: TenseExercise[] = ${JSON.stringify(draft.exercises.map(({ id, stage, level, sentence, options, trans, explain }) => ({ id, stage, level, sentence, options, trans, explain })), null, 2)};

export const concept: ConceptSection[] = ${JSON.stringify(draft.concept, null, 2)};
`;
writeFileSync(new URL('../../src/data/lesson9-tenses.ts', import.meta.url), body);
console.log(`lesson 9: ${draft.exercises.length} exercises, ${draft.stages.length} stages`);
